"use client";

import React, { useState } from "react";
import {
  Clock,
  DollarSign,
  HelpCircle,
  Layers,
  Percent,
  TrendingUp,
  Zap,
} from "lucide-react";
import {
  MarketDefinition,
  calculateDaysToMaturity,
  getAssetPriceUsd,
  getMarketUnderlyingApy,
} from "@/lib/markets";
import { LiveMarketSnapshot } from "@/lib/stellar";
import { MarketAnalyticsData } from "@/components/trading/AnalyticsCard.types";

export interface YieldBreakdownCardsProps {
  snapshot?: LiveMarketSnapshot | null;
  market: MarketDefinition;
  analytics?: MarketAnalyticsData | null;
  loading?: boolean;
  className?: string;
  underlyingPriceUsd?: number;
}

interface BentoCardItem {
  id: string;
  label: string;
  value: string;
  subValue?: string;
  accentClass: string;
  icon: React.ReactNode;
  tooltipTitle: string;
  tooltipFormula: string;
  tooltipDesc: string;
}

export function YieldBreakdownCards({
  snapshot,
  market,
  analytics,
  loading = false,
  className = "",
  underlyingPriceUsd,
}: YieldBreakdownCardsProps) {
  const [activeTooltip, setActiveTooltip] = useState<string | null>(null);

  const resolvedPriceUsd =
    underlyingPriceUsd ?? getAssetPriceUsd(market.asset.code);

  const nowSeconds = snapshot?.nowSeconds ?? Math.floor(Date.now() / 1000);
  const isMatured =
    snapshot?.isMatured ?? nowSeconds >= market.maturity;
  const isSlender = market.sySymbol === "sy-sUSDC";

  // 1. Implied APY
  const impliedApy =
    snapshot?.impliedFixedApyPct ??
    (analytics?.impliedApyPct && analytics.impliedApyPct > 0
      ? analytics.impliedApyPct
      : undefined);
  const impliedApyStr =
    loading && !snapshot && !analytics
      ? "..."
      : impliedApy !== undefined
      ? `${impliedApy.toFixed(2)}%`
      : isMatured
      ? "0.00%"
      : "--";

  // 2. Underlying APY (Protocol floating rate benchmark)
  const underlyingApy = getMarketUnderlyingApy(market);
  const underlyingApyStr = `${underlyingApy.toFixed(2)}%`;

  // 3. Fixed APY (Guaranteed at maturity)
  const fixedApy = isMatured ? 0 : impliedApy;
  const fixedApyStr =
    loading && !snapshot && !analytics
      ? "..."
      : fixedApy !== undefined
      ? `${fixedApy.toFixed(2)}%`
      : "--";

  // 4. YT Leverage Multiplier
  const ptPrice = snapshot?.ptPriceInSy ?? (isMatured ? 1.0 : 0);
  const ytPrice =
    snapshot?.ytPriceInSy ??
    (isMatured ? 0.0 : ptPrice > 0 ? Math.max(0, 1.0 - ptPrice) : 0);
  const ytLeverage = !isMatured && ytPrice > 0 ? Math.round(1 / ytPrice) : 0;
  const ytLeverageStr =
    isMatured
      ? "--"
      : loading && !snapshot
      ? "..."
      : snapshot && ytPrice > 0
      ? `${ytLeverage}x`
      : "--";

  // 5. Days to Maturity
  const daysRemaining =
    snapshot?.daysToMaturity ??
    (isMatured ? 0 : calculateDaysToMaturity(market.maturity, nowSeconds));
  const daysStr =
    isMatured
      ? "Matured"
      : loading && !snapshot
      ? "..."
      : `${daysRemaining.toFixed(1)}d`;

  // 6. Pool Depth & TVL
  const ptReserveRaw = snapshot?.state?.total_pt_reserve ?? 0n;
  const syReserveRaw = snapshot?.state?.total_sy_reserve ?? 0n;
  const ptReserve = Number(ptReserveRaw) / 1e7;
  const syReserve = Number(syReserveRaw) / 1e7;
  const ptInSy = ptReserve * ptPrice;
  const tvlUsd =
    analytics?.totalTvlUsdc !== undefined && Number(analytics.totalTvlUsdc) > 0
      ? Number(analytics.totalTvlUsdc) / 1e7
      : (ptInSy + syReserve) * resolvedPriceUsd;

  const tvlStr =
    loading && !snapshot && !analytics
      ? "..."
      : `$${tvlUsd.toLocaleString("en-US", {
          minimumFractionDigits: 0,
          maximumFractionDigits: 0,
        })}`;

  const poolDepthSubValue =
    ptReserve === 0 && syReserve === 0
      ? "0k PT / 0k SY"
      : ptReserve < 1000 && syReserve < 1000
      ? `${ptReserve.toFixed(2)} PT / ${syReserve.toFixed(2)} SY`
      : `${Math.round(ptReserve / 1000)}k PT / ${Math.round(syReserve / 1000)}k SY`;

  const cards: BentoCardItem[] = [
    {
      id: "implied_apy",
      label: "Implied APY",
      value: impliedApyStr,
      subValue: "Market fixed rate",
      accentClass: "text-positive",
      icon: <TrendingUp className="h-4 w-4 text-positive" />,
      tooltipTitle: "Implied APY",
      tooltipFormula: "(1 / P_pt)^(1 / tau) - 1",
      tooltipDesc:
        "Annualized fixed interest rate implied by current market discount.",
    },
    {
      id: "underlying_apy",
      label: "Underlying APY",
      value: underlyingApyStr,
      subValue: isSlender ? "Slender floating rate" : "Blend floating rate",
      accentClass: "text-ink",
      icon: <Layers className="h-4 w-4 text-accent" />,
      tooltipTitle: "Underlying APY",
      tooltipFormula: isSlender ? "Slender Protocol Supply APR" : "Blend Protocol Supply APR",
      tooltipDesc:
        "Floating lending yield generated by underlying collateral reserves.",
    },
    {
      id: "fixed_apy",
      label: "Fixed APY",
      value: fixedApyStr,
      subValue: "Guaranteed at term",
      accentClass: "text-positive",
      icon: <Percent className="h-4 w-4 text-positive" />,
      tooltipTitle: "Fixed APY",
      tooltipFormula: "PT Redemption Payout (1:1)",
      tooltipDesc:
        "Guaranteed return achieved by holding PT to contract maturity.",
    },
    {
      id: "yt_leverage",
      label: "Long Yield Leverage",
      value: ytLeverageStr,
      subValue: isMatured
        ? "Market expired"
        : snapshot || (analytics && ytPrice > 0)
        ? `Cost: ${ytPrice.toFixed(4)} SY`
        : "--",
      accentClass: "text-accent",
      icon: <Zap className="h-4 w-4 text-accent" />,
      tooltipTitle: "YT Leverage Multiplier",
      tooltipFormula: "1 / P_yt",
      tooltipDesc:
        "Capital efficiency multiplier for long yield exposure.",
    },
    {
      id: "maturity_countdown",
      label: "Maturity",
      value: daysStr,
      subValue: (market.maturityIso || "").slice(0, 10),
      accentClass: "text-ink",
      icon: <Clock className="h-4 w-4 text-ink-muted" />,
      tooltipTitle: "Time to Maturity",
      tooltipFormula: "Maturity Timestamp - Now",
      tooltipDesc:
        "Remaining duration until tokens settle for underlying asset.",
    },
    {
      id: "pool_tvl",
      label: "Pool TVL & Depth",
      value: tvlStr,
      subValue: poolDepthSubValue,
      accentClass: "text-ink",
      icon: <DollarSign className="h-4 w-4 text-accent" />,
      tooltipTitle: "Pool Liquidity & TVL",
      tooltipFormula: "(PT_sy + SY_reserves) * Price",
      tooltipDesc:
        "Combined liquidity backing trades in the Yield Space AMM.",
    },
  ];

  return (
    <div className={`w-full ${className}`}>
      <div className="grid grid-cols-1 gap-3 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-6">
        {cards.map((card) => {
          const isTooltipOpen = activeTooltip === card.id;

          return (
            <div
              key={card.id}
              className="glass-card double-bezel-recessed relative rounded-xl p-4 transition-colors hover:border-glass-rim shadow-glass border-glass-rim-subtle"
            >
              {/* Header with Title & Accessible Tooltip Trigger */}
              <div className="flex items-center justify-between text-xs text-ink-secondary">
                <div className="flex items-center font-medium">
                  <span>{card.label}</span>
                </div>

                <div className="relative">
                  <button
                    type="button"
                    onMouseEnter={() => setActiveTooltip(card.id)}
                    onMouseLeave={() => setActiveTooltip(null)}
                    onClick={() =>
                      setActiveTooltip((prev) =>
                        prev === card.id ? null : card.id
                      )
                    }
                    className="p-0.5 text-ink-muted hover:text-ink focus-visible:outline-2 focus-visible:outline-accent active:scale-95 disabled:opacity-50 rounded"
                    aria-label={`About ${card.label}`}
                  >
                    <HelpCircle className="h-3.5 w-3.5" />
                  </button>

                  {/* Accessible Floating Tooltip Popover */}
                  {isTooltipOpen && (
                    <div className="absolute right-0 top-6 z-50 w-56 rounded-xl border border-glass-rim bg-surface-muted/95 p-3 shadow-glass-elevated backdrop-blur-md">
                      <div className="text-xs font-semibold text-ink">
                        {card.tooltipTitle}
                      </div>
                      <div className="tabular-mono mt-1 text-[11px] font-medium text-accent">
                        {card.tooltipFormula}
                      </div>
                      <div className="mt-1 text-[11px] leading-relaxed text-ink-secondary">
                        {card.tooltipDesc}
                      </div>
                    </div>
                  )}
                </div>
              </div>

              {/* Main Metric Value */}
              <div
                suppressHydrationWarning
                className={`tabular-mono mt-2 text-xl font-bold tracking-tight sm:text-2xl ${card.accentClass}`}
              >
                {card.value}
              </div>

              {/* Sub-label or Context */}
              {card.subValue && (
                <div
                  suppressHydrationWarning
                  className={`mt-1 text-xs text-ink-muted ${
                    card.id === "yt_leverage" ||
                    card.id === "maturity_countdown" ||
                    card.id === "pool_tvl"
                      ? "tabular-mono"
                      : ""
                  }`}
                >
                  {card.subValue}
                </div>
              )}
            </div>
          );
        })}
      </div>
    </div>
  );
}
